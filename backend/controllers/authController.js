/* =========================================================
   FORGOT PASSWORD
========================================================= */

const forgotPassword = async (
  req,
  res
) => {
  try {
    const body = req.body || {};

    const { email } = body;

    /* =====================================================
       VALIDATE EMAIL
    ===================================================== */

    if (email === undefined) {
      return res.status(400).json({
        success: false,
        message:
          "Email address is required",
      });
    }

    if (!isValidEmail(email)) {
      return res.status(400).json({
        success: false,
        message:
          "Please enter a valid email address",
      });
    }

    const normalizedEmail =
      normalizeEmail(email);

    /* =====================================================
       FIND CUSTOMER
    ===================================================== */

    const customerResult =
      await pool.query(
        `
        SELECT
          id,
          email,
          is_active
        FROM customers
        WHERE LOWER(email) = $1
        LIMIT 1
        `,
        [normalizedEmail]
      );

    /*
      IMPORTANT:
      Do not reveal whether an account exists.
    */

    const genericResponse = {
      success: true,
      message:
        "If an account exists with this email, a password reset link has been generated.",
    };

    if (
      customerResult.rows.length === 0
    ) {
      return res.json(
        genericResponse
      );
    }

    const customer =
      customerResult.rows[0];

    /* =====================================================
       INACTIVE ACCOUNT
    ===================================================== */

    if (!customer.is_active) {
      return res.json(
        genericResponse
      );
    }

    /* =====================================================
       INVALIDATE OLD TOKENS
    ===================================================== */

    await pool.query(
      `
      UPDATE password_reset_tokens
      SET used_at = CURRENT_TIMESTAMP
      WHERE customer_id = $1
        AND used_at IS NULL
      `,
      [customer.id]
    );

    /* =====================================================
       GENERATE SECURE TOKEN
    ===================================================== */

    const resetToken =
      crypto
        .randomBytes(32)
        .toString("hex");

    /* =====================================================
       HASH TOKEN BEFORE DATABASE STORAGE
    ===================================================== */

    const tokenHash =
      crypto
        .createHash("sha256")
        .update(resetToken)
        .digest("hex");

    /* =====================================================
       TOKEN EXPIRATION
    ===================================================== */

    const expiresAt = new Date(
      Date.now() +
        30 * 60 * 1000
    );

    /* =====================================================
       SAVE TOKEN
    ===================================================== */

    await pool.query(
      `
      INSERT INTO password_reset_tokens (
        customer_id,
        token_hash,
        expires_at
      )
      VALUES ($1, $2, $3)
      `,
      [
        customer.id,
        tokenHash,
        expiresAt,
      ]
    );

    /* =====================================================
       DEVELOPMENT RESET URL
    ===================================================== */

    const frontendUrl =
      process.env.FRONTEND_URL ||
      "http://localhost:5173";

    const resetUrl =
      `${frontendUrl}/reset-password?token=${resetToken}`;

    /*
      Development only.

      Later replace this with an actual email service.
    */

    console.log(
      "\n=========================================="
    );

    console.log(
      "PASSWORD RESET REQUEST"
    );

    console.log(
      "Customer:",
      customer.email
    );

    console.log(
      "Reset URL:"
    );

    console.log(resetUrl);

    console.log(
      "==========================================\n"
    );

    return res.json({
      ...genericResponse,

      /*
        Keep this only while developing.
        Remove before production.
      */
      developmentResetUrl:
        resetUrl,
    });
  } catch (error) {
    console.error(
      "Forgot password error:",
      error
    );

    return res.status(500).json({
      success: false,
      message:
        "Unable to process password reset request",
    });
  }
};

/* =========================================================
   RESET PASSWORD
========================================================= */

const resetPassword = async (
  req,
  res
) => {
  let client;

  try {
    const body = req.body || {};

    const {
      token,
      password,
      confirm_password,
    } = body;

    /* =====================================================
       REQUIRED VALIDATION
    ===================================================== */

    if (
      token === undefined ||
      password === undefined ||
      confirm_password === undefined
    ) {
      return res.status(400).json({
        success: false,
        message:
          "Reset token, password and confirm password are required",
      });
    }

    /* =====================================================
       TOKEN VALIDATION
    ===================================================== */

    if (!isValidResetToken(token)) {
      return res.status(400).json({
        success: false,
        message:
          "Invalid or expired password reset link",
      });
    }

    /* =====================================================
       PASSWORD VALIDATION
    ===================================================== */

    if (!isValidPassword(password)) {
      return res.status(400).json({
        success: false,
        message:
          "Password must be 8-128 characters and contain at least one uppercase letter, one lowercase letter and one number",
      });
    }

    /* =====================================================
       CONFIRM PASSWORD
    ===================================================== */

    if (password !== confirm_password) {
      return res.status(400).json({
        success: false,
        message:
          "Passwords do not match",
      });
    }

    /* =====================================================
       HASH RESET TOKEN
    ===================================================== */

    const tokenHash =
      crypto
        .createHash("sha256")
        .update(token)
        .digest("hex");

    /* =====================================================
       GET DATABASE CLIENT
    ===================================================== */

    client = await pool.connect();

    await client.query("BEGIN");

    /* =====================================================
       FIND RESET TOKEN
    ===================================================== */

    const tokenResult =
      await client.query(
        `
        SELECT
          id,
          customer_id,
          expires_at,
          used_at
        FROM password_reset_tokens
        WHERE token_hash = $1
        LIMIT 1
        FOR UPDATE
        `,
        [tokenHash]
      );

    if (
      tokenResult.rows.length === 0
    ) {
      await client.query("ROLLBACK");

      return res.status(400).json({
        success: false,
        message:
          "Invalid or expired password reset link",
      });
    }

    const resetRecord =
      tokenResult.rows[0];

    /* =====================================================
       CHECK TOKEN USED
    ===================================================== */

    if (resetRecord.used_at) {
      await client.query("ROLLBACK");

      return res.status(400).json({
        success: false,
        message:
          "This password reset link has already been used",
      });
    }

    /* =====================================================
       CHECK TOKEN EXPIRATION
    ===================================================== */

    if (
      new Date(resetRecord.expires_at) <=
      new Date()
    ) {
      await client.query("ROLLBACK");

      return res.status(400).json({
        success: false,
        message:
          "This password reset link has expired",
      });
    }

    /* =====================================================
       FIND CUSTOMER
    ===================================================== */

    const customerResult =
      await client.query(
        `
        SELECT
          id,
          is_active
        FROM customers
        WHERE id = $1
        LIMIT 1
        FOR UPDATE
        `,
        [resetRecord.customer_id]
      );

    if (
      customerResult.rows.length === 0
    ) {
      await client.query("ROLLBACK");

      return res.status(404).json({
        success: false,
        message:
          "Customer account not found",
      });
    }

    const customer =
      customerResult.rows[0];

    /* =====================================================
       CHECK ACCOUNT STATUS
    ===================================================== */

    if (!customer.is_active) {
      await client.query("ROLLBACK");

      return res.status(403).json({
        success: false,
        message:
          "Customer account is inactive",
      });
    }

    /* =====================================================
       HASH NEW PASSWORD
    ===================================================== */

    const passwordHash =
      await bcrypt.hash(
        password,
        12
      );

    /* =====================================================
       UPDATE PASSWORD
    ===================================================== */

    await client.query(
      `
      UPDATE customers
      SET
        password_hash = $1,
        updated_at = CURRENT_TIMESTAMP
      WHERE id = $2
      `,
      [
        passwordHash,
        customer.id,
      ]
    );

    /* =====================================================
       MARK CURRENT TOKEN AS USED
    ===================================================== */

    await client.query(
      `
      UPDATE password_reset_tokens
      SET
        used_at = CURRENT_TIMESTAMP
      WHERE id = $1
      `,
      [resetRecord.id]
    );

    /* =====================================================
       INVALIDATE OTHER RESET TOKENS
    ===================================================== */

    await client.query(
      `
      UPDATE password_reset_tokens
      SET
        used_at = CURRENT_TIMESTAMP
      WHERE customer_id = $1
        AND id <> $2
        AND used_at IS NULL
      `,
      [
        customer.id,
        resetRecord.id,
      ]
    );

    /* =====================================================
       COMMIT
    ===================================================== */

    await client.query("COMMIT");

    return res.json({
      success: true,
      message:
        "Password has been reset successfully. You can now log in with your new password.",
    });
  } catch (error) {
    if (client) {
      try {
        await client.query(
          "ROLLBACK"
        );
      } catch (rollbackError) {
        console.error(
          "Rollback error:",
          rollbackError
        );
      }
    }

    console.error(
      "Reset password error:",
      error
    );

    return res.status(500).json({
      success: false,
      message:
        "Unable to reset password",
    });
  } finally {
    if (client) {
      client.release();
    }
  }
};

